#!/usr/bin/env bash
# Regenerate mac/requirements-mac.txt — the fully pinned dependency set for
# Apple Silicon. Run it after changing requirements_versions.txt,
# requirements_macos.txt, mac/torch.txt or mac/overrides.txt. It runs on any
# OS: uv resolves for the target platform, not the machine it is on.
set -euo pipefail

cd "$(dirname "$0")/.."

uv pip compile \
    --python-platform aarch64-apple-darwin \
    --python-version 3.11 \
    --override mac/overrides.txt \
    --no-header \
    --output-file mac/requirements-mac.txt \
    requirements_versions.txt requirements_macos.txt mac/torch.txt

# Keep the header uv would write, but with the command that actually made it.
{
    echo "# Generated by mac/lock.sh — do not edit by hand."
    echo "# Apple Silicon (aarch64-apple-darwin), Python 3.11."
    cat mac/requirements-mac.txt
} > mac/requirements-mac.txt.tmp
mv mac/requirements-mac.txt.tmp mac/requirements-mac.txt

echo "Wrote mac/requirements-mac.txt"
